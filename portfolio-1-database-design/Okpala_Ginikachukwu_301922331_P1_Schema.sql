-- Bank/FinTech Platform: relational schema and business constraints.
-- Run once in a fresh PostgreSQL database, then load the sample data.
BEGIN;
CREATE SCHEMA portfolio;

CREATE TABLE portfolio.customer (
  customer_id BIGINT NOT NULL,
  full_name TEXT NOT NULL,
  email TEXT NOT NULL,
  created_on DATE NOT NULL,
  CONSTRAINT pk_customer PRIMARY KEY (customer_id),
  CONSTRAINT uq_customer_email UNIQUE (email)
);

CREATE TABLE portfolio.account (
  account_id BIGINT NOT NULL,
  customer_id BIGINT NOT NULL,
  account_number TEXT NOT NULL,
  opened_on DATE NOT NULL,
  balance NUMERIC(18,2) NOT NULL,
  status TEXT NOT NULL,
  is_primary BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT pk_account PRIMARY KEY (account_id),
  CONSTRAINT uq_account_number UNIQUE (account_number),
  CONSTRAINT fk_account_customer
    FOREIGN KEY (customer_id) REFERENCES portfolio.customer (customer_id),
  CONSTRAINT account_balance_nonnegative CHECK (balance >= 0),
  CONSTRAINT account_status_valid
    CHECK (status IN ('active', 'dormant', 'frozen', 'closed'))
);

-- Only TRUE rows participate in this unique index. A customer may therefore
-- hold several non-primary accounts, but at most one primary account.
CREATE UNIQUE INDEX one_primary_account_per_customer
  ON portfolio.account (customer_id)
  WHERE is_primary = TRUE;

CREATE INDEX ix_account_customer_id
  ON portfolio.account (customer_id);

-- A transfer row represents a successfully committed movement of funds.
-- Failed transfers are rolled back and do not remain as successful transfers.
CREATE TABLE portfolio.transfer (
  transfer_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  source_account_id BIGINT NOT NULL,
  destination_account_id BIGINT NOT NULL,
  amount NUMERIC(18,2) NOT NULL,
  transfer_reference TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_transfer PRIMARY KEY (transfer_id),
  CONSTRAINT uq_transfer_reference UNIQUE (transfer_reference),
  CONSTRAINT fk_transfer_source
    FOREIGN KEY (source_account_id) REFERENCES portfolio.account (account_id),
  CONSTRAINT fk_transfer_destination
    FOREIGN KEY (destination_account_id) REFERENCES portfolio.account (account_id),
  CONSTRAINT transfer_amount_positive CHECK (amount > 0),
  CONSTRAINT transfer_distinct_accounts CHECK (source_account_id <> destination_account_id)
);

CREATE TABLE portfolio.ledger_entry (
  entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  account_id BIGINT NOT NULL,
  amount NUMERIC(18,2) NOT NULL,
  entry_type TEXT NOT NULL,
  occurred_at TIMESTAMPTZ NOT NULL,
  reference TEXT,
  transfer_id BIGINT,
  CONSTRAINT pk_ledger_entry PRIMARY KEY (entry_id),
  CONSTRAINT fk_ledger_entry_account
    FOREIGN KEY (account_id) REFERENCES portfolio.account (account_id),
  CONSTRAINT fk_ledger_entry_transfer
    FOREIGN KEY (transfer_id) REFERENCES portfolio.transfer (transfer_id),
  CONSTRAINT ledger_amount_positive CHECK (amount > 0),
  CONSTRAINT ledger_entry_type_valid CHECK (entry_type IN ('debit', 'credit'))
);

CREATE INDEX ix_ledger_entry_account_id
  ON portfolio.ledger_entry (account_id);

CREATE INDEX ix_ledger_entry_occurred_at
  ON portfolio.ledger_entry (occurred_at);

COMMIT;
